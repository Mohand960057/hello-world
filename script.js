const RTL = ["ar", "ur"];
const WHATSAPP_NUMBER = "966500000000"; // TODO: replace with the real company number
let currentLang = "en";

function setLanguage(lang) {
  if (!translations[lang]) lang = "en";
  currentLang = lang;
  const dict = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL.includes(lang) ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const text = dict[el.dataset.i18n];
    if (text) el.textContent = text;
  });
  document.title = dict.brand;
  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  try { localStorage.setItem("op-lang", lang); } catch (e) {}
}

function initialLanguage() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (fromUrl && translations[fromUrl]) return fromUrl;
  try {
    const saved = localStorage.getItem("op-lang");
    if (saved && translations[saved]) return saved;
  } catch (e) {}
  const browser = (navigator.language || "en").slice(0, 2);
  return translations[browser] ? browser : "en";
}

document.querySelectorAll(".lang-switch button").forEach((b) => {
  b.addEventListener("click", () => setLanguage(b.dataset.lang));
});

const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");
menuToggle.addEventListener("click", () => {
  const open = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
navLinks.querySelectorAll("a").forEach((a) => {
  a.addEventListener("click", () => navLinks.classList.remove("open"));
});

// The contact form opens WhatsApp with a pre-filled message (no backend needed).
document.getElementById("contactForm").addEventListener("submit", (e) => {
  e.preventDefault();
  const form = e.target;
  const dict = translations[currentLang];
  const service = form.service.options[form.service.selectedIndex].textContent;
  const lines = [
    `${dict["form.intro"]} ${service}`,
    `${dict["form.name"]}: ${form.name.value}`,
    `${dict["form.phone"]}: ${form.phone.value}`,
    form.message.value
  ].filter(Boolean);
  window.open(`https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(lines.join("\n"))}`, "_blank");
});

document.getElementById("year").textContent = new Date().getFullYear();
